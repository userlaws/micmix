// Offline check of the FiveM voice tuning editor against a copy of a real fivem.cfg (never the live file).
import { build } from 'esbuild';
import { mkdir, readFile, writeFile, copyFile, rm } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import assert from 'node:assert/strict';
import path from 'node:path';
import { createRequire } from 'node:module';
await mkdir('artifacts/fivem-check', { recursive: true });
await build({ entryPoints: ['src/fivem-config.ts'], bundle: true, platform: 'node', format: 'cjs', outfile: 'artifacts/fivem-check/fivem-config.cjs' });
const { applyFivemVoice, readFivemVoice, fivemVoiceTuned, writeFivemVoice, fivemConfigPath, FIVEM_TUNING } = createRequire(import.meta.url)(path.resolve('artifacts/fivem-check/fivem-config.cjs'));

// Fixture: the real file from this PC when present (copied), else a synthetic one in FiveM's exact format.
const real = fivemConfigPath();
let original;
// The live file may already be tuned by MicMix, so the fixture starts from FiveM's defaults.
if (real && existsSync(real)) { original = applyFivemVoice(await readFile(real, 'latin1'), false); console.log('fixture: copy of', real, 'reset to FiveM defaults,', original.length, 'bytes'); }
else original = ['// generated by CitizenFX', 'unbindall', 'rbind pma-voice KEYBOARD LMENU "+radiotalk"', 'seta "cl_nickname" "Player"', 'seta "profile_voiceTalkEnabled" "1"', 'seta "voice_enableNoiseSuppression" "true"', ''].join('\r\n');

const tuned = applyFivemVoice(original, true);
assert.equal(fivemVoiceTuned(original), false, 'fixture must start untuned');
assert.deepEqual(readFivemVoice(tuned), { noiseSuppression: false, bitrate: FIVEM_TUNING.bitrate });
assert.ok(fivemVoiceTuned(tuned));
assert.ok(tuned.includes('seta "voice_enableNoiseSuppression" "false"\r\n'));
assert.ok(tuned.includes('seta "voice_inBitrate" "96000"\r\n'));
assert.equal(applyFivemVoice(tuned, true), tuned, 'tuning is idempotent');
// Every other line survives untouched and in order.
const others = text => text.split('\r\n').filter(line => !/voice_enableNoiseSuppression|voice_inBitrate/.test(line));
assert.deepEqual(others(tuned), others(original), 'all unrelated lines preserved');
assert.equal((tuned.match(/voice_enableNoiseSuppression/g) || []).length, 1, 'exactly one noise line');
assert.equal((tuned.match(/voice_inBitrate/g) || []).length, 1, 'exactly one bitrate line');
assert.ok(!tuned.includes('\n\n') && !/[^\r]\n/.test(tuned), 'CRLF endings kept throughout');
// Bitrate line lands in sorted position (after voice_enableNoiseSuppression, like FiveM's own block).
const lines = tuned.split('\r\n');
assert.ok(lines.indexOf('seta "voice_inBitrate" "96000"') > lines.indexOf('seta "voice_enableNoiseSuppression" "false"'));

// Restore puts FiveM's defaults back: suppression true, no bitrate line, everything else identical.
const restored = applyFivemVoice(tuned, false);
assert.deepEqual(readFivemVoice(restored), { noiseSuppression: true, bitrate: null });
assert.deepEqual(others(restored), others(original));
assert.equal(applyFivemVoice(restored, false), restored, 'restore is idempotent');
// A file FiveM rewrote after a session (bitrate line dropped, suppression kept) is completed again.
const afterFivem = tuned.replace('seta "voice_inBitrate" "96000"\r\n', '');
assert.equal(fivemVoiceTuned(afterFivem), false);
assert.equal(applyFivemVoice(afterFivem, true), tuned);
// Files with no voice lines, LF endings, or a plain `set` line are handled too.
assert.deepEqual(readFivemVoice(applyFivemVoice('seta "a" "1"\n', true)), { noiseSuppression: false, bitrate: 96000 });
assert.equal(applyFivemVoice('', true), 'seta "voice_enableNoiseSuppression" "false"\nseta "voice_inBitrate" "96000"\n');
assert.deepEqual(readFivemVoice('set voice_inBitrate 64000\n'), { noiseSuppression: null, bitrate: 64000 });

// writeFivemVoice edits a copy on disk atomically and reports when nothing changed.
const copy = path.resolve('artifacts/fivem-check/fivem.cfg');
await writeFile(copy, original, 'latin1');
assert.equal(writeFivemVoice(copy, true), tuned);
assert.equal(await readFile(copy, 'latin1'), tuned);
assert.equal(writeFivemVoice(copy, true), null, 'no rewrite when already tuned');
assert.equal(writeFivemVoice(copy, false), restored);
assert.ok(!existsSync(copy + '.micmix-tmp'));
assert.throws(() => writeFivemVoice(copy + '.nope', true), /not found/);
await rm(copy);
console.log('fivem-config checks passed');
